
from typing import Literal

from pydantic import BaseModel, Field


class PracticeEvaluation(BaseModel):
    correctness: int = Field(
        ge=0,
        le=100,
        description="Score for the correctness of the user's answer."
    )

    depth: int = Field(
        ge=0,
        le=100,
        description="Score for depth and completeness of the answer."
    )

    clarity: int = Field(
        ge=0,
        le=100,
        description="Score for clarity and organization of the answer."
    )

    feedback: str = Field(
        description="Specific feedback explaining strengths and improvements."
    )

    weakness_candidate: str | None = Field(
        default=None,
        description="A potential weakness identified during practice, if any."
    )

    is_store_worthy: bool = Field(
        description="Whether this result is useful enough to save in memory."
    )

    memory_tag: str | None = Field(
        default=None,
        description="A suitable tag for a store-worthy memory, if applicable."
    )


class PracticeQuestion(BaseModel):
    """One mock-interview question generated for the user."""

    topic: str = Field(min_length=1, description="Skill or topic the question tests.")

    question: str = Field(min_length=10, description="The interview question.")

    expected_concepts: list[str] = Field(
        min_length=2,
        max_length=10,
        description="Concepts a strong answer should cover; used to grade the answer.",
    )

    difficulty: Literal["easy", "medium", "hard"] = Field(
        description="Difficulty relative to the user's demonstrated level."
    )

    why_this_question: str = Field(
        min_length=1,
        description="Why this question was chosen for this user (gap, weakness or role).",
    )

    source_refs: list[str] = Field(
        default_factory=list,
        description="Existing gap, weakness or evidence reference IDs. Never invent IDs.",
    )


class PracticeQuestionSet(BaseModel):
    """Questions generated by the Practice agent."""

    questions: list[PracticeQuestion] = Field(min_length=1, max_length=5)
